// write puts one file under dir, creating what it needs on the way.
func write(t *testing.T, dir, rel, content string) string {
	t.Helper()
	p := filepath.Join(dir, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
	return p
}

// The counts come from the profile itself rather than `go tool cover
// -func`, which only runs from inside the module a profile came from — see
// goProfileLines' doc comment.
func TestGoProfileLines(t *testing.T) {
	dir := t.TempDir()
	// 3 of 4 statements covered.
	path := write(t, dir, "cover.out", "mode: set\n"+
		"fixture/main.go:3.13,5.2 2 1\n"+
		"fixture/main.go:7.13,7.20 1 3\n"+
		"fixture/main.go:9.13,9.20 1 0\n")

	got, err := goProfileLines(GoModuleProfile{Profile: path, ModuleName: "fixture"}, dir)
	if err != nil {
		t.Fatal(err)
	}
	if got != (LineCount{Covered: 3, Total: 4}) {
		t.Fatalf("goProfileLines = %+v, want {3 4}", got)
	}
	if got.Percent() != 75 {
		t.Fatalf("Percent() = %v, want 75", got.Percent())
	}
}

// A profile with no coverable statement in it says nothing about the
// component, so it must not be reported as 0% — that would drag a baseline
// down with a number no test run could ever move, and would fail a per-unit
// floor no work could clear.
func TestGoProfileLinesEmptyIsUnmeasured(t *testing.T) {
	dir := t.TempDir()
	path := write(t, dir, "cover.out", "mode: set\n")
	got, err := goProfileLines(GoModuleProfile{Profile: path, ModuleName: "fixture"}, dir)
	if err != nil {
		t.Fatal(err)
	}
	if got.Measured() {
		t.Fatalf("goProfileLines = %+v, want unmeasured", got)
	}
}

// Generated code arrives in large, entirely-uncovered blocks nobody is going
// to hand-test. Left in the denominator it dominates the aggregate: wardnet's
// generated REST client alone drags its SDK module to 2%.
func TestGoProfileLinesExcludeGeneratedFiles(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "rest.gen.go", "// Code generated by openapi-codegen. DO NOT EDIT.\n"+
		"\npackage rest\n\nfunc Gen() {\n\tprintln(1)\n}\n")
	write(t, dir, "hand.go", "package rest\n\nfunc Hand() {\n\tprintln(1)\n}\n")
	// The generated file is entirely uncovered and the hand-written one
	// covered: counting both would give 50%, only the latter counts.
	path := write(t, dir, "cover.out", "mode: set\n"+
		"fixture/rest.gen.go:5.13,7.2 1 0\n"+
		"fixture/hand.go:3.14,5.2 1 1\n")

	got, err := goProfileLines(GoModuleProfile{Profile: path, ModuleName: "fixture"}, dir)
	if err != nil {
		t.Fatal(err)
	}
	if got.Percent() != 100 {
		t.Fatalf("goProfileLines = %+v, want 100%%", got)
	}
}

// `go list -m` above a module root answers "command-line-arguments" — not an
// error, and not a prefix any profile entry carries. Treating it as a module
// path strips nothing and every file silently fails to match the diff, which
// is how Go patch coverage came to be reported as unmeasured in wardnet.
func TestModuleNameRejectsNonModuleDir(t *testing.T) {
	if got := moduleName(context.Background(), t.TempDir()); got != "" {
		t.Fatalf("moduleName(non-module dir) = %q, want \"\"", got)
	}
}

// An lcov's counts come from its LF and LH records, never from tallying its DA
// lines. The two disagree — measured against the proving ground's three-crate
// workspace, 57 lines by LF and 55 by DA — because a line carrying more than
// one record is one line to LF and two to a tally. A DA tally would report a
// denominator smaller than the tool's own, against a baseline the same tool
// recorded.
func TestLCOVCountsComeFromTheSummaryRecords(t *testing.T) {
	// Two records for line 4, which is what makes the two counts differ.
	lcov := "SF:src/lib.rs\n" +
		"DA:1,1\nDA:2,0\nDA:4,1\nDA:4,0\n" +
		"LF:4\nLH:3\n" +
		"end_of_record\n"
	lines, hits := ParseLCOV([]byte(lcov), t.TempDir())
	if lines != (LineCount{Covered: 3, Total: 4}) {
		t.Errorf("ParseLCOV counts = %+v, want {3 4} from LF/LH", lines)
	}
	if got := len(hits["src/lib.rs"]); got != 3 {
		t.Errorf("hits = %v, want 3 distinct lines", hits["src/lib.rs"])
	}
}

// Measure reads one component's report and produces both quantities every
// gate is built from, out of the one artefact its instrumented run wrote.
func TestMeasureReadsAGoProfile(t *testing.T) {
	root := t.TempDir()
	write(t, root, "svc/go.mod", "module example.com/svc\n\ngo 1.26\n")
	write(t, root, "svc/main.go", "package svc\n\nfunc F(b bool) int {\n\tif b {\n\t\treturn 1\n\t}\n\treturn 0\n}\n")
	write(t, root, "svc/.lydite-reports/coverage.out", "mode: set\n"+
		"example.com/svc/main.go:3.20,4.10 1 1\n"+
		"example.com/svc/main.go:4.10,6.3 1 0\n")

	got, err := Measure(context.Background(), root, "svc", ".lydite-reports/coverage.out", runner.Go)
	if err != nil {
		t.Fatal(err)
	}
	if got.Lines != (LineCount{Covered: 1, Total: 2}) {
		t.Errorf("Lines = %+v, want {1 2}", got.Lines)
	}
	// Keyed the way git names the file: the module path is stripped and the
	// component's own directory put back on. Neither implies the other.
	if _, ok := got.Hits["svc/main.go"]; !ok {
		t.Errorf("Hits keys = %v, want svc/main.go", keys(got.Hits))
	}
}

// Two components each holding a src/index.ts produce the same lcov-relative
// path. Without the component's own directory put back on, one silently
// overwrites the other and the patch gate scores one component's lines
// against another's coverage.
func TestMeasurePrefixesLCOVPathsWithTheComponentDirectory(t *testing.T) {
	root := t.TempDir()
	lcov := "SF:src/index.ts\nDA:1,1\nDA:2,0\nLF:2\nLH:1\nend_of_record\n"
	write(t, root, "web/.lydite-reports/lcov.info", lcov)
	write(t, root, "admin/.lydite-reports/lcov.info", lcov)

	for _, dir := range []string{"web", "admin"} {
		got, err := Measure(context.Background(), root, dir, ".lydite-reports/lcov.info", runner.TypeScript)
		if err != nil {
			t.Fatal(err)
		}
		want := dir + "/src/index.ts"
		if _, ok := got.Hits[want]; !ok {
			t.Errorf("%s: Hits keys = %v, want %q", dir, keys(got.Hits), want)
		}
	}
}

// A component rooted at the scan root has no prefix to add, and adding "."
// would key every file under a directory git never names.
func TestMeasureAtTheScanRootAddsNoPrefix(t *testing.T) {
	root := t.TempDir()
	write(t, root, ".lydite-reports/lcov.info", "SF:src/lib.rs\nDA:1,1\nLF:1\nLH:1\nend_of_record\n")
	got, err := Measure(context.Background(), root, ".", ".lydite-reports/lcov.info", runner.Rust)
	if err != nil {
		t.Fatal(err)
	}
	if _, ok := got.Hits["src/lib.rs"]; !ok {
		t.Errorf("Hits keys = %v, want src/lib.rs", keys(got.Hits))
	}
}

// A report lydite cannot read is an error naming it, never a zero
// measurement. A component that measured nothing and one whose report lydite
// failed to find are different states, and collapsing them is how a gate that
// could not run comes to read as one that passed.
func TestMeasureRefusesAMissingReport(t *testing.T) {
	root := t.TempDir()
	_, err := Measure(context.Background(), root, "web", ".lydite-reports/lcov.info", runner.TypeScript)
	if err == nil {
		t.Fatal("Measure returned no error for a report that does not exist")
	}
	if !strings.Contains(err.Error(), "lcov.info") {
		t.Errorf("error %q does not name the report it looked for", err)
	}
}

// A Go component whose directory is not a module root cannot have its
// profile's package-qualified paths resolved, and `go list -m` answers
// "command-line-arguments" there rather than failing. Reported as an error, so
// it cannot be mistaken for a measurement.
func TestMeasureRefusesAGoComponentThatIsNotAModuleRoot(t *testing.T) {
	root := t.TempDir()
	write(t, root, "svc/.lydite-reports/coverage.out", "mode: set\n")
	_, err := Measure(context.Background(), root, "svc", ".lydite-reports/coverage.out", runner.Go)
	if err == nil {
		t.Fatal("Measure returned no error for a directory holding no go.mod")
	}
}

func keys(h LineHits) []string {
	out := make([]string, 0, len(h))
	for k := range h {
		out = append(out, k)
	}
	return out
}
